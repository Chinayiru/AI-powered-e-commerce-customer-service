def main() -> None:
    KB.parent.mkdir(parents=True, exist_ok=True)
    EVAL.parent.mkdir(parents=True, exist_ok=True)

    with KB.open("w", encoding="utf-8") as fh:
        for qa_id, cat, q, a, tags, _ in DOCS:
            assert len(a) <= 200, qa_id
            fh.write(json.dumps({
                "qa_id": qa_id, "question": q, "answer": a, "category": cat,
                "tags": tags, "source": "policy_manual_v1", "status": "approved",
            }, ensure_ascii=False) + "\n")

    n = 0
    with EVAL.open("w", encoding="utf-8") as fh:
        for qa_id, cat, _, _, _, queries in DOCS:
            for i, query in enumerate(queries, 1):
                n += 1
                fh.write(json.dumps({
                    "query_id": f"Q{n:03d}", "query": query, "gold": [qa_id], "category": cat,
                }, ensure_ascii=False) + "\n")
    print(f"wrote {len(DOCS)} qa docs, {n} labeled queries")


if __name__ == "__main__":
    main()
